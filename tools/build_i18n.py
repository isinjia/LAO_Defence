"""Builds js/i18n_data.js from tools/i18n_table.py (Korean source string -> translations).
  python tools/build_i18n.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import i18n_table as I  # noqa: E402


def main():
    n = len(I.LANGS) - 1
    t = {}
    for row in I.T:
        assert len(row) == n + 1, row[0]
        assert row[0] not in t, "duplicate key: " + row[0]
        t[row[0]] = list(row[1:])
    data = {"langs": I.LANGS, "labels": I.LABELS, "t": t}
    with open(os.path.join(HERE, "..", "js", "i18n_data.js"), "w", encoding="utf-8") as f:
        f.write("// generated by tools/build_i18n.py from tools/i18n_table.py\n")
        f.write("window.I18N_DATA=%s;\n" % json.dumps(data, ensure_ascii=False, separators=(",", ":")))
    print("i18n:", len(t), "strings x", n, "languages")
    import stamp_build
    stamp_build.main()


if __name__ == "__main__":
    main()
